// Renders a fixture through the remote provider, as docs/design/render-runtime.md has it (phase 1): MinIO and the media-tools
// image's `cf-job serve` run in Docker on a network of their own, the inputs and outputs travel as presigned URLs, and the
// runner reaches MinIO only through its allowlist (the URLs are signed for the host's MinIO port, which the runner dials as
// minio:9000, as compose's runner profile does). The sources are generated by a first remote job, so nothing is mounted
// from the host. Needs Docker and a built image, so it only runs when asked (CI's media-tools job does):
//
//	go test ./internal/render -run IntegrationRemote -docker-image media-tools:dev
func TestIntegrationRemoteRender(t *testing.T) {
	if *dockerImage == "" {
		t.Skip("set -docker-image to run the Docker integration test")
	}
	ctx, cancel := context.WithTimeout(context.Background(), 15*time.Minute)
	defer cancel()

	nw, err := network.New(ctx)
	if err != nil {
		t.Fatal(err)
	}
	t.Cleanup(func() { _ = nw.Remove(context.Background()) })

	minio := startContainer(ctx, t, testcontainers.ContainerRequest{
		Image:          storagetest.Image,
		Cmd:            []string{"server", "/tmp/data"},
		ExposedPorts:   []string{"9000/tcp"},
		Env:            map[string]string{"MINIO_ROOT_USER": storagetest.AccessKey, "MINIO_ROOT_PASSWORD": storagetest.SecretKey},
		Networks:       []string{nw.Name},
		NetworkAliases: map[string][]string{nw.Name: {"minio"}},
		WaitingFor:     wait.ForHTTP("/minio/health/ready").WithPort("9000/tcp").WithStartupTimeout(2 * time.Minute),
	})
	objectsAddr := hostPort(ctx, t, minio, "9000/tcp")
	cfg := storage.Config{Endpoint: "http://" + objectsAddr, Bucket: "remote-render", AccessKeyID: storagetest.AccessKey, SecretAccessKey: storagetest.SecretKey}
	if _, err := storagetest.S3(cfg).CreateBucket(ctx, &s3.CreateBucketInput{Bucket: aws.String(cfg.Bucket)}); err != nil {
		t.Fatal(err)
	}
	objects, err := storage.New(cfg)
	if err != nil {
		t.Fatal(err)
	}

	const token = "remote-render-test-token-0123456789"
	tmpfs := "rw,noexec,nosuid,nodev,size=1g,mode=1777"
	runner := startContainer(ctx, t, testcontainers.ContainerRequest{
		Image:        *dockerImage,
		Cmd:          []string{"cf-job", "serve", "-addr", ":8080"},
		ExposedPorts: []string{"8080/tcp"},
		Env: map[string]string{
			"CF_JOB_TOKEN": token, "CF_JOB_CPUS": "4", "CF_JOB_MEMORY_MB": "8192",
			"CF_JOB_ALLOWED_HOSTS": objectsAddr, "CF_JOB_DIAL": objectsAddr + "=minio:9000",
		},
		Tmpfs:      map[string]string{"/in": tmpfs, "/work": tmpfs, "/tmp": tmpfs},
		Networks:   []string{nw.Name},
		WaitingFor: wait.ForHTTP("/healthz").WithPort("8080/tcp").WithStartupTimeout(time.Minute),
	})
	remote, err := sandbox.NewRemote("http://"+hostPort(ctx, t, runner, "8080/tcp"), token)
	if err != nil {
		t.Fatal(err)
	}
	remote.PollInterval = 200 * time.Millisecond

	// The fixture's plan, with its inputs at placeholder paths: only their container paths and the keys behind them matter.
	cat := testAssets(t)
	spec := loadFixture(t, "v08_transition_crossfade", cat)
	plan, err := Compile(spec, Preview, ResolverFunc(func(id string, _ Variant) (ResolvedAsset, error) {
		return ResolvedAsset{Location: "/src/" + id + ".mp4", HasAudio: true}, nil
	}))
	if err != nil {
		t.Fatal(err)
	}
	if plan.Motion != nil || plan.Bed != nil || (plan.Loudnorm != nil && plan.Loudnorm.TwoPass) || plan.StemLabel != "" {
		t.Fatal("the fixture's preview plan needs more than one encode; this test renders single-pass plans")
	}
	inputs, err := mountInputs(plan.Inputs)
	if err != nil {
		t.Fatal(err)
	}
	limits := DefaultLimits()
	presignPut := func(key, contentType string) string {
		u, err := objects.PresignPut(ctx, key, contentType, limits.Timeout)
		if err != nil {
			t.Fatal(err)
		}
		return u
	}
	presignGet := func(key string) string {
		u, err := objects.PresignGet(ctx, key, limits.Timeout)
		if err != nil {
			t.Fatal(err)
		}
		return u
	}

	// Job 1 makes the sources: 16 s of video with audio for every distinct input (the fixture reads up to 15 s).
	keyOf := map[string]string{} // container path -> source key
	gen := sandbox.Job{ID: "rnd_sources-1", Limits: limits}
	for _, in := range inputs {
		if _, ok := keyOf[in.Container]; ok {
			continue
		}
		n := strconv.Itoa(len(keyOf))
		keyOf[in.Container] = "src/" + n + ".mp4"
		gen.Steps = append(gen.Steps, sandbox.Step{Args: []string{"ffmpeg", "-nostdin", "-v", "error", "-y",
			"-f", "lavfi", "-i", "testsrc2=size=640x360:rate=30:duration=16", "-f", "lavfi", "-i", "sine=frequency=330:sample_rate=48000:duration=16",
			"-c:v", "libx264", "-preset", "ultrafast", "-pix_fmt", "yuv420p", "-c:a", "aac", media.OutputPath("src" + n + ".mp4")}})
		gen.Outputs = append(gen.Outputs, sandbox.Output{Path: media.OutputPath("src" + n + ".mp4"), URL: presignPut(keyOf[in.Container], "video/mp4"), ContentType: "video/mp4"})
	}
	if res, err := remote.Run(ctx, gen); err != nil || res.ExitCode != 0 {
		t.Fatalf("generate the sources: %+v %v", res, err)
	}

	// Job 2 renders the plan, probes the result and cuts a poster from it, in one sandbox that downloads the footage once. The
	// subtitles (the preview's watermark) arrive as an input instead of being written into the work directory, and the image's
	// own fonts are used.
	if err := objects.Put(ctx, "src/subs.ass", strings.NewReader(plan.Subtitles.ASS), int64(len(plan.Subtitles.ASS)), "text/plain"); err != nil {
		t.Fatal(err)
	}
	render := sandbox.Job{ID: "rnd_render-1", Limits: limits}
	for container, key := range keyOf {
		render.Inputs = append(render.Inputs, sandbox.Input{URL: presignGet(key), Path: container})
	}
	render.Inputs = append(render.Inputs, sandbox.Input{URL: presignGet("src/subs.ass"), Path: "/in/subs.ass"})
	args := useImageFonts(plan.Args, plan.Subtitles)
	for i, a := range args {
		args[i] = strings.ReplaceAll(a, "filename="+plan.Subtitles.File, "filename=/in/subs.ass")
	}
	encode := append(ffmpegPrefix("error", "progress-render.txt"), containerArgs(args, inputs)...)
	encode = append(encode, "-y", media.OutputPath(outName))
	render.Steps = []sandbox.Step{
		{Args: encode},
		{Args: []string{"ffprobe", "-v", "error", "-show_entries", "stream=codec_type,width,height:format=duration", "-of", "json", media.OutputPath(outName)}},
		{Args: []string{"ffmpeg", "-nostdin", "-v", "error", "-y", "-ss", "1", "-i", media.OutputPath(outName), "-frames:v", "1", media.OutputPath("poster.jpg")}},
	}
	render.Outputs = []sandbox.Output{
		{Path: media.OutputPath(outName), URL: presignPut("renders/out.mp4", "video/mp4"), ContentType: "video/mp4", MaxBytes: 64 << 20},
		{Path: media.OutputPath("poster.jpg"), URL: presignPut("renders/poster.jpg", "image/jpeg"), ContentType: "image/jpeg"},
	}
	res, err := remote.Run(ctx, render)
	if err != nil || res.ExitCode != 0 || len(res.Steps) != 3 {
		t.Fatalf("render: %+v %v", res, err)
	}
	var probe struct {
		Streams []struct {
			CodecType string `json:"codec_type"`
			Width     int    `json:"width"`
			Height    int    `json:"height"`
		} `json:"streams"`
		Format struct {
			Duration string `json:"duration"`
		} `json:"format"`
	}
	if err := json.Unmarshal(res.Steps[1].Stdout, &probe); err != nil {
		t.Fatalf("ffprobe output %q: %v", res.Steps[1].Stdout, err)
	}
	var video, audio bool
	for _, s := range probe.Streams {
		switch s.CodecType {
		case "video":
			video = s.Width == plan.OutputSize.Width && s.Height == plan.OutputSize.Height
		case "audio":
			audio = true
		}
	}
	secs, _ := strconv.ParseFloat(probe.Format.Duration, 64)
	if !video || !audio || math.Abs(secs*1000-float64(plan.DurationMs)) > 100 {
		t.Errorf("rendered %+v; plan %+v, %d ms", probe, plan.OutputSize, plan.DurationMs)
	}
	for key, ct := range map[string]string{"renders/out.mp4": "video/mp4", "renders/poster.jpg": "image/jpeg"} {
		info, err := objects.Head(ctx, key)
		if err != nil || info.Size == 0 || info.ContentType != ct {
			t.Errorf("%s in the bucket: %+v %v", key, info, err)
		}
	}

	// The runner refuses a URL outside its allowlist before it fetches anything.
	stray := sandbox.Job{ID: "rnd_stray-1", Limits: limits, Args: []string{"ffprobe", "/in/0"},
		Inputs: []sandbox.Input{{URL: "http://example.com/clip.mp4", Path: "/in/0"}}}
	if _, err := remote.Run(ctx, stray); err == nil || errors.Is(err, sandbox.ErrSandbox) || !strings.Contains(err.Error(), "not one this runner may reach") {
		t.Errorf("a URL outside the allowlist: %v", err)
	}
	// A failing step is a result, with the tool's stderr.
	bad := sandbox.Job{ID: "rnd_bad-1", Limits: limits, Args: []string{"ffprobe", "-v", "error", "/work/none.mp4"}}
	if res, err := remote.Run(ctx, bad); err != nil || res.ExitCode == 0 || !bytes.Contains(res.Stderr, []byte("none.mp4")) {
		t.Errorf("a failing tool: %+v %v", res, err)
	}
}

func startContainer(ctx context.Context, t *testing.T, req testcontainers.ContainerRequest) testcontainers.Container {
	t.Helper()
	ctr, err := testcontainers.GenericContainer(ctx, testcontainers.GenericContainerRequest{ContainerRequest: req, Started: true})
	if ctr != nil {
		t.Cleanup(func() { _ = ctr.Terminate(context.Background()) })
	}
	if err != nil {
		t.Fatalf("start %s: %v", req.Image, err)
	}
	return ctr
}

func hostPort(ctx context.Context, t *testing.T, ctr testcontainers.Container, port string) string {
	t.Helper()
	host, err := ctr.Host(ctx)
	if err != nil {
		t.Fatal(err)
	}
	p, err := ctr.MappedPort(ctx, port)
	if err != nil {
		t.Fatal(err)
	}
	return net.JoinHostPort(host, p.Port())
}
