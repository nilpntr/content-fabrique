// Command gen writes metrics_gen.go: the layout tables of the vendored fonts, read from the font files with style.ParseFont.
//
//	go generate ./internal/timeline/style
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/format"
	"log"
	"os"
	"path/filepath"

	"github.com/nilpntr/content-fabrique/internal/timeline/style"
)

func main() {
	fonts := flag.String("fonts", "", "directory with the font files")
	out := flag.String("out", "metrics_gen.go", "file to write")
	flag.Parse()
	if *fonts == "" {
		log.Fatal("gen: -fonts is required")
	}
	var b bytes.Buffer
	b.WriteString("// Code generated by gen (go generate ./internal/timeline/style); DO NOT EDIT.\n\npackage style\n\n")
	b.WriteString("// generatedTables holds the layout tables of the fonts in packages/media-tools/fonts, by file name.\n")
	b.WriteString("var generatedTables = map[string]*FontTable{\n")
	for _, f := range style.FontFiles() {
		data, err := os.ReadFile(filepath.Join(*fonts, f)) //nolint:gosec // a generator reading the vendored fonts
		if err != nil {
			log.Fatal(err)
		}
		ff, err := style.ParseFont(data)
		if err != nil {
			log.Fatalf("%s: %v", f, err)
		}
		t := style.BuildTable(ff)
		fmt.Fprintf(&b, "\t%q: {\n\t\tUnitsPerEm: %d, WinAscent: %d, WinDescent: %d, Notdef: %d,\n\t\tRuns: []AdvRun{", f, t.UnitsPerEm, t.WinAscent, t.WinDescent, t.Notdef)
		for i, r := range t.Runs {
			if i%4 == 0 {
				b.WriteString("\n\t\t\t")
			} else {
				b.WriteString(" ")
			}
			fmt.Fprintf(&b, "{0x%04X, %d, %d},", r.First, r.Off, r.N)
		}
		b.WriteString("\n\t\t},\n\t\tAdv: []uint16{")
		for i, a := range t.Adv {
			if i%16 == 0 {
				b.WriteString("\n\t\t\t")
			} else {
				b.WriteString(" ")
			}
			fmt.Fprintf(&b, "%d,", a)
		}
		b.WriteString("\n\t\t},\n\t},\n")
	}
	b.WriteString("}\n")
	src, err := format.Source(b.Bytes())
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile(*out, src, 0o600); err != nil { //nolint:gosec // generated source
		log.Fatal(err)
	}
}
