const (
	glyphW  = 5
	glyphH  = 7
	glyphSP = 1
)

// textWidth is the width in pixels of text drawn at scale.
func textWidth(text string, scale int) int {
	n := len([]rune(text))
	if n == 0 {
		return 0
	}
	return (n*(glyphW+glyphSP) - glyphSP) * scale
}

// drawText draws text (upper-cased; a character with no glyph is a space) with its top left corner at (x, y).
func drawText(dst *image.RGBA, x, y, scale int, c color.Color, text string) {
	for _, ch := range strings.ToUpper(text) {
		if g, ok := glyphs[ch]; ok {
			for row, line := range g {
				for col, p := range line {
					if p == '#' {
						fillRect(dst, image.Rect(x+col*scale, y+row*scale, x+(col+1)*scale, y+(row+1)*scale), c)
					}
				}
			}
		}
		x += (glyphW + glyphSP) * scale
	}
}

// fillRect paints r with c (over the existing pixels when c has alpha), clipped to the image.
func fillRect(dst *image.RGBA, r image.Rectangle, c color.Color) {
	r = r.Intersect(dst.Bounds())
	if r.Empty() {
		return
	}
	draw.Draw(dst, r, image.NewUniform(c), image.Point{}, draw.Over)
}
