// RuntimeGVisor is the name Docker knows gVisor's runsc by (daemon.json "runtimes").
const RuntimeGVisor = "runsc"

// nobody is the unprivileged identity used when the worker itself runs as root.
const nobody = 65534

// Docker runs jobs with `docker run`. Used as is it is the `docker` provider (development); with Runtime set to
// RuntimeGVisor it is the `hardened` provider (NewHardened).
//
// Every container gets: no network, a read-only root filesystem, a private tmpfs on /tmp, all capabilities dropped,
// no-new-privileges, a non-root user, memory (swap included), CPU and PID limits, no IPC namespace sharing and no
// credentials (the environment is exactly HOME and TMPDIR). Images are never pulled at job time.
type Docker struct {
	Policy
	// Binary is the docker CLI; default "docker".
	Binary string
	// Runtime is passed as --runtime when non-empty.
	Runtime string
	// ProviderName is what Name returns; default "docker".
	ProviderName string
	// User is "uid:gid" for the container process; default is the worker's own uid:gid (so it can read the files it
	// staged and files written to the output directory belong to it), or 65534:65534 when the worker runs as root. A job
	// whose mounts that user cannot access is refused with ErrInputUnreadable before docker starts.
	User string
	// TmpSizeMB is the size of the /tmp tmpfs; default 256.
	TmpSizeMB int
}

// NewDocker returns the docker provider.
func NewDocker(policy Policy) *Docker { return &Docker{Policy: policy} }

// NewHardened returns the hardened provider: the docker provider under gVisor. If runsc is not registered with the
// Docker daemon, jobs fail; there is no fallback to the default runtime.
func NewHardened(policy Policy) *Docker {
	return &Docker{Policy: policy, Runtime: RuntimeGVisor, ProviderName: "hardened"}
}

// Name implements Provider.
func (d *Docker) Name() string {
	if d.ProviderName != "" {
		return d.ProviderName
	}
	return "docker"
}

func (d *Docker) binary() string {
	if d.Binary != "" {
		return d.Binary
	}
	return "docker"
}

// Run implements Provider.
func (d *Docker) Run(ctx context.Context, job Job) (Result, error) {
	v, err := d.validate(job, true)
	if err != nil {
		return Result{}, err
	}
	uid, gid := os.Getuid(), os.Getgid()
	user, chown := userFor(uid, gid, d.User)
	if chown {
		for _, m := range v.mounts {
			if m.Writable {
				if err := os.Chown(m.Host, nobody, nobody); err != nil {
					return Result{}, fmt.Errorf("sandbox: chown output dir for the container user: %w", err)
				}
			}
		}
	}
	if err := checkAccess(v.mounts, user); err != nil {
		return Result{}, err
	}
	name, err := containerName()
	if err != nil {
		return Result{}, err
	}
	args := d.buildArgs(v, name, user)

	runCtx, cancel := context.WithTimeout(ctx, v.Limits.Timeout)
	defer cancel()
	cmd := exec.CommandContext(runCtx, d.binary(), args...) // #nosec G204 -- argv is built by buildArgs from validated fields; no shell
	stdout, stderr := newBoundedBuffer(v.maxOutput), newBoundedBuffer(v.maxOutput)
	cmd.Stdout, cmd.Stderr = stdout, stderr
	cmd.WaitDelay = 10 * time.Second

	start := time.Now()
	runErr := cmd.Run()
	res := Result{Duration: time.Since(start)}
	res.Stdout, res.StdoutTruncated = stdout.snapshot()
	res.Stderr, res.StderrTruncated = stderr.snapshot()

	kill, err := finish(runCtx, ctx.Err(), cmd, runErr, v.Limits.Timeout, false, &res)
	if kill {
		// Killing the docker CLI does not stop the container; do that by name.
		d.kill(name)
	}
	if err != nil {
		return res, err
	}
	switch res.ExitCode {
	case 125, 126, 127:
		// `docker run` itself failed (daemon error, missing image or runtime) or could not start the program.
		return res, fmt.Errorf("%w: docker run exited %d: %s", ErrSandbox, res.ExitCode, snippet(res.Stderr))
	}
	return res, nil
}

// snippet is the start of a tool's stderr for an error message.
func snippet(b []byte) string {
	const limit = 512
	if len(b) > limit {
		b = b[:limit]
	}
	return strings.TrimSpace(string(b))
}

// kill force-removes the container and waits until it is gone: a timed-out job must not leave one behind. `docker rm --force` can
// fail when the container is already being removed (`--rm` and the kill race), so it is repeated, a few times, until `docker
// inspect` no longer finds the container. Errors are ignored: the container may never have been created.
func (d *Docker) kill(name string) {
	ctx, cancel := context.WithTimeout(context.Background(), 30*time.Second)
	defer cancel()
	for attempt := 0; attempt < 10 && ctx.Err() == nil; attempt++ {
		_ = exec.CommandContext(ctx, d.binary(), "rm", "--force", name).Run()                                                 // #nosec G204 -- name is generated by containerName
		if exec.CommandContext(ctx, d.binary(), "inspect", "--type", "container", "--format", "{{.Id}}", name).Run() != nil { // #nosec G204 -- same
			return // not found: gone
		}
		time.Sleep(200 * time.Millisecond)
	}
}

// userFor returns the container user for a worker running as uid:gid. An explicit override wins. Only a worker that is
// really root (uid 0) switches to the unprivileged nobody, and then the output directory must be chowned to it; a worker
// with a non-zero uid keeps its own uid and gid, even gid 0, because uid is what grants root's powers.
func userFor(uid, gid int, override string) (user string, chown bool) {
	if override != "" {
		return override, false
	}
	if uid == 0 {
		return fmt.Sprintf("%d:%d", nobody, nobody), true
	}
	return fmt.Sprintf("%d:%d", uid, gid), false
}

func containerName() (string, error) {
	var b [8]byte
	if _, err := rand.Read(b[:]); err != nil {
		return "", fmt.Errorf("sandbox: container name: %w", err)
	}
	return "cf-sbx-" + hex.EncodeToString(b[:]), nil
}

// buildArgs returns the argument list for `docker run`. It is a pure function of its inputs, golden-tested.
func (d *Docker) buildArgs(v validated, name, user string) []string {
	tmp := d.TmpSizeMB
	if tmp <= 0 {
		tmp = 256
	}
	mem := strconv.Itoa(v.Limits.MemoryMB) + "m"
	a := []string{
		"run", "--rm",
		"--name", name,
		"--pull", "never",
		"--network", "none",
		"--read-only",
		"--cap-drop", "ALL",
		"--security-opt", "no-new-privileges",
		"--ipc", "none",
		"--user", user,
		"--pids-limit", strconv.Itoa(v.Limits.PIDs),
		"--memory", mem,
		"--memory-swap", mem,
		"--cpus", strconv.FormatFloat(v.Limits.CPU, 'f', -1, 64),
		"--ulimit", "nofile=1024:1024",
		"--ulimit", "core=0",
		"--tmpfs", "/tmp:rw,noexec,nosuid,nodev,mode=1777,size=" + strconv.Itoa(tmp) + "m",
		"--env", "HOME=/tmp",
		"--env", "TMPDIR=/tmp",
	}
	if d.Runtime != "" {
		a = append(a, "--runtime", d.Runtime)
	}
	keys := make([]string, 0, len(v.Labels))
	for k := range v.Labels {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	for _, k := range keys {
		a = append(a, "--label", "cf."+k+"="+v.Labels[k])
	}
	for _, m := range v.mounts {
		a = append(a, "--mount", mountSpec(m))
	}
	a = append(a, v.Image)
	return append(a, v.Args...)
}

// mountSpec renders a bind mount for --mount. The source is CSV-quoted because Docker parses the value as CSV, so a
// path with a comma, quote or colon is data, never another option. Container paths are restricted to plain characters.
func mountSpec(m resolvedMount) string {
	src := `"src=` + strings.ReplaceAll(m.Host, `"`, `""`) + `"`
	s := "type=bind," + src + ",dst=" + m.Container
	if !m.Writable {
		s += ",readonly"
	}
	return s
}
